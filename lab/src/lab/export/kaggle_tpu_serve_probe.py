def harness_env(wheelhouse, venvs, data_dir, sub):
    """Build `harness` on CPython 3.13 from the pinned harness wheels plus PyPI, add the task wheels, then prove the
    runner imports what it needs and that reference patches pass in the subprocess sandbox."""
    py = str(venvs / "harness/bin/python")
    wheels = sorted(str(w) for w in wheelhouse.glob("*.whl") if w.name.split("-")[0].lower() in HARNESS_WHEELS)
    (WORK / "constraints.txt").write_text(CONSTRAINTS)
    # Managed CPython only: the TPU image's /usr/bin/python3.13 lacks ensurepip, so the sandbox's per-task venv fails.
    rc = sh([sys.executable, "-m", "uv", "venv", "--python", HARNESS_PYTHON, "--python-preference", "only-managed",
             str(venvs / "harness")], "install.log")
    rc = rc or sh([sys.executable, "-m", "uv", "pip", "install", "--python", py, "--torch-backend", "cpu",
                   "--constraint", str(WORK / "constraints.txt"), *wheels],
                  "install.log")
    task_wheels, check = [], None
    if not rc:
        p = subprocess.run([py, "-c", TASK_WHEELS, str(data_dir / "wheels")], capture_output=True, text=True)
        task_wheels = json.loads(p.stdout) if p.returncode == 0 else []
        rc = p.returncode or not task_wheels or sh([sys.executable, "-m", "uv", "pip", "install", "--python", py,
                                                    "--no-deps", *task_wheels], "install.log")
        if p.returncode:
            (OUT / "install.log").open("a").write(p.stderr)
    if not rc:
        p = subprocess.run([py, "-c", "import importlib, sys; [importlib.import_module(m) for m in sys.argv[1:]]",
                            *HARNESS_IMPORTS], capture_output=True, text=True)
        h = subprocess.run([py, str(WORK / "run_eval.py"), "--help"], capture_output=True, text=True)
        (WORK / "gold_check.py").write_text(GOLD_CHECK)
        try:
            g = subprocess.run([py, str(WORK / "gold_check.py"), str(data_dir), str(sub), str(OUT / "gold"),
                                *GOLD_TASKS], capture_output=True, text=True, timeout=1200)
        except subprocess.TimeoutExpired as e:
            g = subprocess.CompletedProcess(e.cmd, 124, "", "gold check timed out")
        (OUT / "gold_check.log").write_text(f"rc {{g.returncode}}\\n--- stdout\\n{{g.stdout}}\\n--- stderr\\n{{g.stderr}}")
        gold = next((json.loads(line[5:]) for line in g.stdout.splitlines() if line.startswith("GOLD [")), None)
        check = {{"imports_rc": p.returncode, "help_rc": h.returncode, "gold_rc": g.returncode, "gold": gold,
                  "stderr": (p.stderr + h.stderr + g.stderr[-1500:])[-2000:]}}
        rc = p.returncode or h.returncode or g.returncode
        sh([sys.executable, "-m", "uv", "pip", "freeze", "--python", py], "harness_freeze.txt")
    stage("harness", rc=rc, python=HARNESS_PYTHON, wheels=[Path(w).name for w in wheels],
          task_wheels=len(task_wheels), check=check, minutes=round((time.time() - T0) / 60, 1))
    if rc:
        sys.exit(5)
    return py


def post(base, body, timeout=600):
    req = urllib.request.Request(base + "/chat/completions", data=json.dumps(body).encode(),
                                 headers={{"Content-Type": "application/json"}})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return json.loads(r.read())


