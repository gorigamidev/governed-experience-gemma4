def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--zip", type=Path, default=ROOT / "build/bf/submission.zip")
    ap.add_argument("--arms", default="", help="name=zip,...; default: bf=--zip")
    ap.add_argument("--task-ids", default="", help="comma-separated; default: the three probe tasks")
    ap.add_argument("--slug", default=SLUG)
    ap.add_argument("--out", type=Path, default=ROOT / "build/tpu-serve-probe")
    ap.add_argument("--budget-min", type=int, default=150)
    ap.add_argument("--round-min", type=int, default=15, help="stop when less than this is left")
    a = ap.parse_args()
    arm_zips = dict(item.split("=", 1) for item in a.arms.split(",") if item) or {"bf": str(a.zip)}
    arms = {}
    for name, path in arm_zips.items():
        data = Path(path).read_bytes()
        arms[name] = (hashlib.sha256(data).hexdigest(), base64.b64encode(data).decode())
    tasks = [t for t in a.task_ids.split(",") if t] or TASKS
    runner = (ROOT / "lab/src/lab/eval/run_eval.py").read_bytes()
    script = SCRIPT.format(arms=arms,
                           runner_sha=hashlib.sha256(runner).hexdigest(), runner_b64=base64.b64encode(runner).decode(),
                           tasks=tasks, vllm_tpu=VLLM_TPU, budget=a.budget_min, round_min=a.round_min,
                           harness_wheels=HARNESS_WHEELS, harness_python=HARNESS_PYTHON, gold_tasks=GOLD_TASKS,
                           harness_imports=HARNESS_IMPORTS,
                           constraints=(Path(__file__).with_name("tpu_harness_constraints.txt")).read_text(),
                           model_token=f"{MODEL}-it-qat-q4_0-unquantized").replace("# __MERGE__", MERGE)
    compile(script, a.slug, "exec")  # fail here, not on Kaggle
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / f"{a.slug}.py").write_text(script)
    meta = {"id": f"{OWNER}/{a.slug}", "title": a.slug.replace("-", " "), "code_file": f"{a.slug}.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": False, "enable_tpu": True,
            "enable_internet": True, "keywords": [], "dataset_sources": [WHEELHOUSE], "kernel_sources": [],
            "competition_sources": [COMPETITION], "model_sources": [bf16_source(MODEL)], "machine_shape": "TpuV6E8"}
    (a.out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    print(f"kernel {meta['id']} -> {a.out} | " + " ".join(f"{n} {sha[:12]}" for n, (sha, _) in arms.items())
          + f" | budget {a.budget_min} min | {len(tasks)} tasks: {','.join(tasks)}")


if __name__ == "__main__":
    main()
