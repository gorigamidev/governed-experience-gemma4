"""TPU serve probe (doc 03 §14.34, "Recursos sin usar" 2): can a Kaggle TPU v5e-8 serve the 31B with vllm-tpu and run
the `bf` agent on 3 tasks? Script kernel with internet on (not a submission), so vllm-tpu and uv come from PyPI.
With --arms and --task-ids it runs several packages on the same tasks, interleaved per task as the GPU pool notebook
does (results/<arm>/ in the same layout), to measure rule compliance on TPU (§14.34, plan of 23 Oct).

Two virtualenvs, because the competition wheelhouse pins a CUDA vLLM/torch: `harness` gets the harness wheels of the
wheelhouse (pinned) with the rest of their dependencies from PyPI, pinned by `tpu_harness_constraints.txt`, and a
CPU torch; `serve` gets vllm-tpu.
The wheelhouse is a delta over the Kaggle GPU image, so `--no-deps` into an empty venv misses `pyyaml` and the rest
(v1 died there, LOG 22 oct). `harness` is built and import-checked before `serve`, so that failure costs minutes.
The subprocess sandbox installs no task dependencies (swegemma skips it for SubprocessSandbox): tasks see whatever
`harness` has. On GPU the Kaggle image supplies pytest and the rest; here `harness` runs CPython 3.13, like the
scorer's sandbox, and gets the competition's task wheels on top (the scorer's py313 set, deduplicated, without
replacing harness dists). The TPU pool of 23 Oct ran on 3.12 without them: no pytest in any task (LOG 24 oct).
A gold check verifies reference patches of GOLD_TASKS in that sandbox before serving.
The runner is `lab/eval/run_eval.py`, embedded verbatim. Every stage rewrites `probe/report.json`.

With TPU_PROBE_LOCAL=<api_base>|<served_model>|<data_dir>[|<wheelhouse_dir>] the same script skips the server and
runs the agent against an existing OpenAI-compatible server (local rehearsal with Ollama). With a wheelhouse dir it
builds and checks the `harness` venv as on the TPU; without one it uses the current interpreter.

Usage: PYTHONPATH=lab/src python3 -m lab.export.kaggle_tpu_serve_probe [--out build/tpu-serve-probe]
       ... --slug gemma4-tpu-pool-gov --arms bf=build/bf/submission.zip,bf-gov=build/bf-gov/submission.zip \
           --task-ids rich_3006,... --budget-min 330 --out build/tpu-pool-gov
"""

