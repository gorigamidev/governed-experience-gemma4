"""TPU smoke kernel: runs `lab/lora/tpu_smoke.py` on the 31B bf16 checkpoint on a Kaggle TPU (script kernel).

The kernel embeds `train.py` and `tpu_smoke.py` verbatim, finds its inputs by a file they must contain (mount paths
have moved before), and runs the smoke test in a subprocess so a crash still leaves the report and the log.
Nothing it trains is used.

Usage: PYTHONPATH=lab/src python3 -m lab.export.kaggle_tpu_smoke [--out build/tpu-smoke]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from lab.export.kaggle_eval_notebook import OWNER
from lab.export.models import bf16_source

ROOT = Path(__file__).resolve().parents[4]
SOURCES = {name: ROOT / "lab/src/lab/lora" / name for name in ("train.py", "tpu_smoke.py")}
LORA_DATA = "gorigamidev/gemma4-lora-data"
LORA_WHEELS = "gorigamidev/gemma4-lora-wheels"
MODEL = "31b"
SLUG = "gemma4-tpu-smoke"
MACHINE = "TpuV6E8"  # the shape the TPU probe asked for; it ran on 8 TPU v5 lite chips (16 GB each)

SCRIPT = '''"""TPU smoke test of the behavior LoRA (generated by lab/export/kaggle_tpu_smoke.py; do not edit)."""
import json, subprocess, sys
from pathlib import Path

SOURCES = {sources}
WORK = Path("/kaggle/working")
for name, text in SOURCES.items():
    (WORK / name).write_text(text)


def find(pattern, must_contain=""):
    hits = sorted(p for p in Path("/kaggle/input").rglob(pattern) if must_contain in str(p))
    if not hits:
        print("missing", pattern, must_contain, "| /kaggle/input:", sorted(str(p) for p in Path("/kaggle/input").glob("*/*/*"))[:60])
        sys.exit(2)
    return hits[0].parent


model = find("config.json", "{model_token}")
data = find("requests.jsonl")
wheels = find("peft-*.whl")
print("model", model, "| data", data, "| wheels", wheels, flush=True)
cmd = [sys.executable, str(WORK / "tpu_smoke.py"), "--model", str(model), "--data", str(data),
       "--peft-wheels", str(wheels), "--out", str(WORK / "smoke"), "--budget-min", "{budget}"]
rc = subprocess.run(cmd).returncode
report = WORK / "smoke" / "tpu_smoke_report.json"
print("exit", rc, "| report", report.exists(), flush=True)
if report.exists():
    print(report.read_text(), flush=True)
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=ROOT / "build/tpu-smoke")
    ap.add_argument("--budget-min", type=int, default=150)
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    sources = {name: path.read_text() for name, path in SOURCES.items()}
    script = SCRIPT.format(sources=repr(sources), model_token=f"{MODEL}-it-qat-q4_0-unquantized", budget=a.budget_min)
    compile(script, SLUG, "exec")  # fail here, not on Kaggle
    (a.out / f"{SLUG}.py").write_text(script)
    meta = {"id": f"{OWNER}/{SLUG}", "title": SLUG.replace("-", " "), "code_file": f"{SLUG}.py", "language": "python",
            "kernel_type": "script", "is_private": True, "enable_gpu": False, "enable_tpu": True,
            "enable_internet": False, "keywords": [], "dataset_sources": [LORA_DATA, LORA_WHEELS],
            "kernel_sources": [], "competition_sources": [], "model_sources": [bf16_source(MODEL)],
            "machine_shape": MACHINE}
    (a.out / "kernel-metadata.json").write_text(json.dumps(meta, indent=1))
    print(f"kernel {meta['id']} -> {a.out} | model {bf16_source(MODEL)}")


if __name__ == "__main__":
    main()
